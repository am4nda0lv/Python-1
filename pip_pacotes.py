# pip é o gerenciador de pacotes do Python. Ele permite instalar e gerenciar
# bibliotecas externas que adicionam funcionalidades aos programas.
#
# Instalar um ou mais pacotes:
# pip install pandas folium
#
# Instalar pacotes listados no arquivo requirements.txt:
# pip install -r requirements.txt
#
# Listar os pacotes instalados:
# pip freeze